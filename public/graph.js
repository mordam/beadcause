/* Graph tab: bd's own dependency graph, in an iframe, scoped to one bead or the
   whole workspace.

   The page it frames is generated by `bd graph --html` and served by /api/graph —
   we draw none of it. All this does is choose the scope, put the token on the URL
   and give you a way back, because the framed page has no chrome of its own.

   The token rides in the query string for the same reason it does for a PDF in the
   reader tab: an iframe cannot carry a header. It never leaves the tailnet, and
   /api/graph accepts it exactly as every other endpoint does. */
(() => {
  'use strict';

  const params = new URLSearchParams(location.search);
  const workspace = params.get('ws') || '';
  const bead = params.get('id') || '';
  const token = localStorage.getItem('beadcause.token') || '';

  const main = document.getElementById('graph-main');
  const titleEl = document.getElementById('graph-title');
  const scopeEl = document.getElementById('scope');

  // No bead means there is nothing to narrow to, so the switch would be a no-op.
  let scope = bead ? params.get('scope') || 'bead' : 'all';

  document.getElementById('graph-close').addEventListener('click', () => {
    window.close();
    setTimeout(() => (location.href = '/'), 120);
  });

  function fail(msg) {
    main.innerHTML = `<div class="empty"><strong>Can't draw this graph</strong>${msg}</div>`;
  }

  function draw() {
    const q = new URLSearchParams({ workspace, t: token });
    if (scope === 'bead' && bead) q.set('id', bead);

    const label = scope === 'bead' && bead ? bead : workspace;
    titleEl.textContent = label;
    document.title = `${label} · graph`;

    for (const btn of scopeEl.querySelectorAll('.scope-btn')) {
      btn.classList.toggle('on', btn.dataset.scope === scope);
    }

    // Replaced rather than re-pointed: the framed page runs a D3 force simulation,
    // and reusing the element leaves the old one settling behind the new load.
    const frame = document.createElement('iframe');
    frame.className = 'graph-frame';
    frame.title = `Dependency graph for ${label}`;
    frame.src = `/api/graph?${q}`;
    main.replaceChildren(frame);
  }

  if (!workspace) return fail('No workspace given.');
  if (!token) return fail('This device is not paired. Open the inbox first.');

  if (bead) {
    scopeEl.hidden = false;
    scopeEl.addEventListener('click', (ev) => {
      const btn = ev.target.closest('.scope-btn');
      if (!btn || btn.dataset.scope === scope) return;
      scope = btn.dataset.scope;
      draw();
    });
  }

  draw();
})();
